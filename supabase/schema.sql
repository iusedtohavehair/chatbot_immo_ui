-- Tables de base. À exécuter une fois dans Supabase > SQL Editor.

create table if not exists public.landlord (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text null,
  active boolean null,
  constraint landlord_pkey primary key (id)
);

create table if not exists public.buildings (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text null,
  address text null,
  city text null,
  zip text null,
  landlord text null,
  active boolean null default true,
  constraint buildings_pkey primary key (id)
);

create table if not exists public.tenants (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text null,
  phone text null,
  email text null,
  active boolean null,
  constraint tenants_pkey primary key (id)
);

create table if not exists public.doors (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text null,
  tenants text null,
  active boolean null,
  building text null,
  constraint doors_pkey primary key (id)
);

create table if not exists public.tickets (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  owner text null,
  door text null,
  priority numeric null,
  state numeric null,
  title text null,
  summary text null,
  text text null,
  category text null,
  is_deleted boolean null default false,
  constraint tickets_pkey primary key (id)
);
