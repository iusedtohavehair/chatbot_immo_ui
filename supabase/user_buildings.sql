-- Associe un utilisateur à plusieurs immeubles, avec un rôle par immeuble.
-- À exécuter APRÈS users.sql. Peut être ré-exécuté sans risque.

alter table public.users drop column if exists landlord;

create table if not exists public.user_buildings (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null references public.users (id) on delete cascade,
  building bigint not null references public.buildings (id) on delete cascade,
  role text not null default 'concierge'
    check (role in ('concierge', 'gestionnaire', 'proprietaire', 'technicien')),
  constraint user_buildings_pkey primary key (id),
  constraint user_buildings_unique unique (user_id, building, role)
);

-- Immeubles de l'utilisateur connecté (tous rôles confondus).
create or replace function public.my_building_ids()
returns setof bigint
language sql
stable
security definer
set search_path = ''
as $$
  select ub.building
  from public.user_buildings ub
  join public.users u on u.id = ub.user_id
  where ub.user_id = auth.uid() and u.active;
$$;

alter table public.user_buildings enable row level security;

drop policy if exists "admin full access" on public.user_buildings;
create policy "admin full access" on public.user_buildings
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "read own buildings" on public.user_buildings;
create policy "read own buildings" on public.user_buildings
  for select to authenticated using (user_id = auth.uid());

-- Lecture pour la future plateforme : chacun voit les immeubles, logements
-- et tickets de TOUS ses immeubles. Le tri par immeuble se fait côté interface.
-- nullif(...::text, '')::bigint fonctionne que les colonnes soient text ou bigint (migration_fk.sql).

drop policy if exists "read my buildings" on public.buildings;
create policy "read my buildings" on public.buildings
  for select to authenticated using (id in (select public.my_building_ids()));

drop policy if exists "read my doors" on public.doors;
create policy "read my doors" on public.doors
  for select to authenticated
  using (nullif(building::text, '')::bigint in (select public.my_building_ids()));

drop policy if exists "read my tickets" on public.tickets;
create policy "read my tickets" on public.tickets
  for select to authenticated
  using (
    nullif(door::text, '')::bigint in (
      select d.id from public.doors d
      where nullif(d.building::text, '')::bigint in (select public.my_building_ids())
    )
  );
